        developerName: String,
        projectName: String,
        seed: String
    ): String {
        val pool = greetings.getValue(archetype)
        val pick = pool[abs(seed.hashCode()) % pool.size]
        return pick
            .replace("{dev}", developerName)
            .replace("{name}", projectName)
    }

