package com.s0dolamby.game.data.registry

import com.s0dolamby.game.domain.model.PersonaArchetype
import com.s0dolamby.game.domain.model.Project
import com.s0dolamby.game.domain.model.ProjectFate
import kotlin.math.abs
import kotlin.random.Random

/**
 * Скриптовый «разбор старца» после закрытия дела. Заменяет LLM-вызов
 * GeneratePostMortemUseCase: все факты (судьба, архетип, P&L, поведение
 * игрока) известны детерминированно, а текст собирается из четырёх блоков:
 *
 *   1. Что это было         — по судьбе дела
 *   2. Как себя выдавал     — по архетипу хозяина (приметы для летописи)
 *   3. Твой итог            — по вложению и знаку P&L
 *   4. Урок на будущее      — по судьбе × задавал ли игрок вопросы
 *
 * По 2–3 варианта на блок → сотни непохожих комбинаций. Выбор — по seed
 * от id проекта: разбор не «переигрывается» при повторном открытии.
 * Бонус: мгновенно и офлайн, спиннер «старец думает» больше не нужен.
 */
object PostMortemScribe {

    fun compose(project: Project, questionCount: Int): String {
        val rng = Random(abs(project.id.hashCode()).toLong())
        val invested = project.investedAmountRubles
        val pnl = project.currentValueRubles - invested

        val parts = listOf(
            fateIntro(project, rng),
            archetypeTell(project.personaArchetype, rng),
            outcome(project, invested, pnl, rng),
            lesson(project.fate, questionCount, invested, rng)
        )
        return parts.joinToString(" ")
    }

    // ─── 1. Что это было ────────────────────────────────────────────────────

    private fun fateIntro(project: Project, rng: Random): String {
        val n = project.claimedName
        return when (project.fate) {
            ProjectFate.INSTANT_SCAM -> listOf(
                "«$n» с самого начала было чистым обманом — приумножать вклады тут никто не собирался.",
                "Дело «$n» оказалось скорым мошенничеством: собрать гроши и исчезнуть — весь его замысел.",
                "«$n» — классическая ловушка: громкие посулы, пустая казна и хозяин, готовый раствориться в ночи."
            ).random(rng)
            ProjectFate.SLOW_DRAIN -> listOf(
                "«$n» тонуло медленно: доходы таяли, а хозяин до последнего делал вид, что всё идёт по плану.",
                "Дело «$n» было дырявой лодкой — вода прибывала месяцами, но наружу этого не выносили.",
                "«$n» выцеживало вклады потихоньку: не грабёж средь бела дня, а долгое тихое обескровливание."
            ).random(rng)
            ProjectFate.HONEST_FAIL -> listOf(
                "«$n» было честным делом — просто не сошлась экономика. Такое случается и без злого умысла.",
                "Хозяин «$n» не обманывал: рынок оказался сильнее. Честный провал — тоже провал, но не грех.",
                "Дело «$n» велось искренне, да не выгорело — конкуренты и обстоятельства съели прибыль."
            ).random(rng)
            ProjectFate.SURVIVOR -> listOf(
                "«$n» оказалось крепким ремеслом: без чудес, но с настоящим стабильным доходом.",
                "Дело «$n» жило честным трудом — скромная, но верная прибыль, как и обещалось.",
                "«$n» — редкий случай, когда слова хозяина и приходные книги сошлись."
            ).random(rng)
            ProjectFate.UNICORN -> listOf(
                "«$n» — та самая жар-птица: редкое дело, что действительно взлетело и озолотило вкладчиков.",
                "Дело «$n» оказалось настоящим сокровищем — такие рождаются одно на десяток.",
                "«$n» превзошло даже посулы хозяина — а это в наших краях чудо чудное."
            ).random(rng)
        }
    }

    // ─── 2. Как себя выдавал хозяин ─────────────────────────────────────────

    private fun archetypeTell(archetype: PersonaArchetype, rng: Random): String = when (archetype) {
        PersonaArchetype.BURATINO -> listOf(
            "Хозяин был из породы простодушных вралей: сам верил своим выдумкам, поминал «больших покровителей» и обещал деревья с монетами. Такие не злодеи — но гроши у них тают одинаково.",
            "Балабольство и сказки про Поле Чудес — верная примета этого типа: чем красивее байка, тем меньше за ней правды."
        ).random(rng)
        PersonaArchetype.BOYARIN -> listOf(
            "Пышные титулы, «род от царя Гороха» и грамоты в ларцах, которых никто не видел, — так узнаётся вельможный пускатель пыли в глаза.",
            "Хозяин прятался за величием предков: чем громче родословная, тем тише ответы на прямые вопросы."
        ).random(rng)
        PersonaArchetype.KOLOBOK -> listOf(
            "Хозяин от любого неудобного вопроса укатывался с прибауткой — бодрость вместо ответов и есть его почерк.",
            "«От всех ушёл» — любимая песня таких дельцов. От ответственности перед вкладчиками, как выясняется, уходят так же легко."
        ).random(rng)
        PersonaArchetype.KOSCHEI -> listOf(
            "Холодные цифры как приговоры и уверенность в собственном бессмертии — почерк узнаваемый. Только цифры надо было проверять в чужих книгах, не в его.",
            "Хозяин говорил числами и презирал эмоции — выглядит надёжно, но и точные цифры бывают выдуманы очень точно."
        ).random(rng)
        PersonaArchetype.ZOLUSHKA -> listOf(
            "Давление на жалость, «успей до полуночи» и подруженьки, которые «все уже вложились», — приметы искусной игры на чувствах.",
            "История «из грязи в князи» трогает сердце — потому её и рассказывают каждому встречному."
        ).random(rng)
        PersonaArchetype.BABA_YAGA -> listOf(
            "Загадки вместо ответов и «лес знает» — так уходят от сути. Мудрость хороша в сказках, в денежных делах нужна ясность.",
            "Хозяйка отвечала туманом и образами — за туманом легко спрятать и правду, и её отсутствие."
        ).random(rng)
        PersonaArchetype.IVAN_DURAK -> listOf(
            "Хозяин не приукрашивал и недостатков не прятал — редкое качество. Искренность не гарантирует прибыли, но с такими хотя бы знаешь, на что идёшь.",
            "Простые слова без давления и дедлайнов — почерк честного простака. Иногда его надежды сбываются, иногда нет, но карты были на столе."
        ).random(rng)
    }

    // ─── 3. Твой итог ───────────────────────────────────────────────────────

    private fun outcome(project: Project, invested: Double, pnl: Double, rng: Random): String {
        val isScam = project.fate == ProjectFate.INSTANT_SCAM || project.fate == ProjectFate.SLOW_DRAIN
        return when {
            invested <= 0.0 && isScam -> listOf(
                "Ты не вложил ни гроша — и правильно: чутьё сберегло твою казну.",
                "Ты остался в стороне, и на этот раз осторожность оказалась чистой прибылью."
            ).random(rng)
            invested <= 0.0 -> listOf(
                "Ты наблюдал со стороны: гроши целы, но и прибыль прошла мимо.",
                "Ты не вложился — казна цела, а вот удача на сей раз досталась другим."
            ).random(rng)
            pnl > 0 -> listOf(
                "Твой итог: вложено ${fmt(invested)}, получено ${fmt(project.currentValueRubles)} — прибыль ${fmt(pnl)}. Достойная сделка.",
                "Счёт таков: ${fmt(invested)} вложено, ${fmt(project.currentValueRubles)} вернулось. ${fmt(pnl)} прибытка — в добрый час."
            ).random(rng)
            pnl < 0 -> listOf(
                "Из вложенных ${fmt(invested)} вернулось лишь ${fmt(project.currentValueRubles)} — потеря ${fmt(-pnl)}. Горько, но наука дороже.",
                "Итог печален: минус ${fmt(-pnl)} от вложенных ${fmt(invested)}. Утешает одно — опыт таких денег стоит."
            ).random(rng)
            else -> "Вышел ровно в ноль — вложенные ${fmt(invested)} вернулись до гроша. Ни прибыли, ни потерь."
        }
    }

    // ─── 4. Урок на будущее ─────────────────────────────────────────────────

    private fun lesson(fate: ProjectFate, questionCount: Int, invested: Double, rng: Random): String {
        val isScam = fate == ProjectFate.INSTANT_SCAM || fate == ProjectFate.SLOW_DRAIN
        return when {
            isScam && questionCount == 0 && invested > 0 -> listOf(
                "И запомни: ты не задал хозяину ни одного вопроса. Пара прямых вопросов о выплатах — и обман выдал бы себя куда раньше.",
                "Урок прост: вкладывать не поговорив — что нырять не глядя. Спрашивай о выплатах и сроках, там ложь и рвётся."
            ).random(rng)
            isScam && questionCount > 0 -> listOf(
                "Ты расспрашивал хозяина — верный подход: уклончивые ответы и есть главный красный флаг таких дел.",
                "Беседа — твоё оружие: чем настойчивее вопросы, тем быстрее сыплется красивая сказка."
            ).random(rng)
            fate == ProjectFate.HONEST_FAIL -> listOf(
                "Запомни: не всякий провал — обман. Смотри на суть дела, а не только на манеры хозяина.",
                "Урок таков: честного человека тоже может подвести рынок. Различай злой умысел и злую судьбу."
            ).random(rng)
            fate == ProjectFate.SURVIVOR -> listOf(
                "Приметь на будущее: скромные посулы и ровные ответы — так выглядит настоящее дело. Сравнивай с крикунами.",
                "Урок: где обещают мало, но выполняют — там и стоит держать гроши."
            ).random(rng)
            else -> listOf(
                "Но помни: жар-птицы редки, одна на десяток. Радуйся удаче — и не жди её от каждого дела.",
                "Не обольщайся: такое везение — исключение. Завтра под теми же речами может прятаться пустышка."
            ).random(rng)
        }
    }

    private fun fmt(amount: Double): String = "${amount.toLong()} г"

    private fun <T> List<T>.random(rng: Random): T = this[rng.nextInt(size)]
}
