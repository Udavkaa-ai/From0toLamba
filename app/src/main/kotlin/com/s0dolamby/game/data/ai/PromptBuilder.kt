/**
 * Персона дельца для AMA-беседы — текст 1:1 из tg/server/src/ai/openRouterClient.ts.
 * Заменяет более механическую persona из personas.json (та остаётся для lieTopics).
 */
private data class AmaPersona(
    val speechStyle: String,
    val favoriteTopics: String,
    val typicalPhrases: List<String>
)

@Singleton
class PromptBuilder @Inject constructor() {

    fun buildAmaSystemPrompt(
        project: Project,
        persona: DeveloperPersona,
        questionCount: Int
    ): String {
        val amaPersona = AMA_PERSONAS[project.personaArchetype]
        val phrases = (amaPersona?.typicalPhrases ?: persona.typicalPhrasesTemplate)
            .joinToString("\n") { "- ${it.replace("{name}", project.claimedName)}" }
        val speechStyle = amaPersona?.speechStyle ?: persona.speechStyle
        val favoriteTopics = amaPersona?.favoriteTopics ?: ""
        val fateBehavior = FATE_BEHAVIOR[project.fate] ?: ""

        return """
Ты играешь роль в текстовой игре «Из грязи в князи» — сказочная Русь, беседа с дельцом. Игрок может спрашивать о чём угодно: о тебе, о деле, о жизни, попросить байку.

Твой персонаж: ${project.developerName}, хозяин дела «${project.claimedName}». Отвечай только от его имени.

ХАРАКТЕР И МАНЕРА РЕЧИ: $speechStyle

ЛЮБИМЫЕ ТЕМЫ ДЛЯ БОЛТОВНИ: $favoriteTopics

ХАРАКТЕРНЫЕ ФРАЗЫ (используй как образец стиля, не копируй дословно):
$phrases

СКРЫТАЯ СУТЬ ДЕЛА (только для тебя — не говори об этом напрямую, но дай почувствовать):
$fateBehavior

ПРАВИЛА:
- Отвечай 2-3 предложения, живым современным русским. Без длинных монологов.
- Не выходи из роли. Каждый ответ начинай по-разному.
- Суммы — только в грошах (г). Никакой крипты, TON, блокчейна.
- Не объясняй игроку «я персонаж такой-то». Просто будь им.
- Если игрок задал странный/мета-вопрос — отшутись в характере и переведи тему на свои байки.
        """.trimIndent()
    }

    // Остальные промпты удалены за ненадобностью — вся генерация, кроме
    // живых ответов в чате, переведена на локальные банки:
    //   приветствие дельца  → data/registry/GreetingBank
    //   имена дельцов       → data/registry/DeveloperNameBank
    //   ежедневные вести    → data/registry/NewsTemplateBank
    //   разбор старца       → data/registry/PostMortemScribe
    //   обложки дел         → сток-ассеты (assets/banners/)
}
