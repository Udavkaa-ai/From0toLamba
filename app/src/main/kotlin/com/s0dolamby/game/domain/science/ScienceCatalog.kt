    private val byId: Map<String, ScienceCard> = ALL.associateBy { it.id }
    fun byId(id: String): ScienceCard? = byId[id]

    private val archetypeCards: Map<PersonaArchetype, List<String>> = mapOf(
        PersonaArchetype.ZOLUSHKA to listOf("polunoch", "podruzhenki", "zhalost"),
        PersonaArchetype.KOSCHEI to listOf("tochnye_cifry", "garantiya"),
        PersonaArchetype.BOYARIN to listOf("avtoritet", "titul"),
        PersonaArchetype.KOLOBOK to listOf("ukhod", "pozitiv"),
        PersonaArchetype.BABA_YAGA to listOf("tuman", "ekspert"),
        PersonaArchetype.BURATINO to listOf("skazka", "pokrovitel"),
        PersonaArchetype.IVAN_DURAK to listOf("chestnoe_lico")
    )

    private val fateCard: Map<ProjectFate, String> = mapOf(
        ProjectFate.INSTANT_SCAM to "bystrye_dengi",
        ProjectFate.SLOW_DRAIN to "piramida",
        ProjectFate.HONEST_FAIL to "chestnyi_proval",
        ProjectFate.SURVIVOR to "skromnost",
        ProjectFate.UNICORN to "zhar_ptica"
    )

    /**
     * Кандидаты для закрытого дела в порядке приоритета: сперва приёмы
     * архетипа хозяина, затем карта судьбы, затем особые обстоятельства.
     */
    fun candidatesFor(project: Project): List<ScienceCard> = buildList {
        archetypeCards[project.personaArchetype]?.forEach { id -> byId[id]?.let(::add) }
        fateCard[project.fate]?.let { id -> byId[id]?.let(::add) }
        if (project.isWithdrawalLocked) byId["zamorozka"]?.let(::add)
    }
