        )
    )

    /** Детерминированно по projectId выбирает шаблон. Один проект — одно предложение. */
    fun pick(projectId: String): MafiaOffer {
        val seed = projectId.sumOf { it.code }
        return ALL[seed % ALL.size]
    }

    /** Чёткая финальная инструкция для игрока — добавляется ко всем мафио-вестям. */
    private const val CTA =
        "⚡ Покинь дело сейчас (Казна → Покинуть дело) — заберёшь всё. " +
            "Дотянешь до автозакрытия — получишь только половину."

    /** Подставляет {name} в шаблон и добавляет CTA отдельным абзацем. */
    fun renderWarning(offer: MafiaOffer, projectName: String): String =
        offer.warning.replace("{name}", "«$projectName»") + "\n\n" + CTA
}
