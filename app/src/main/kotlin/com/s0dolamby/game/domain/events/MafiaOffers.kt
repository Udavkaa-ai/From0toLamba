            warning = "У ворот {name} стоят люди в чёрных кафтанах — пришли с предложением: либо в долю, либо беда.",
            closure = "Чёрные кафтаны забрали свою долю — вкладчикам половина, остальное «на расходы»"
        ),
        MafiaOffer(
            id = "tsar_buyout",
            warning = "Государыня приметила {name} — готовится указ о принудительном выкупе в казну.",
            closure = "Государев выкуп прошёл — казна забрала половину, вкладчикам остаток"
        ),
        MafiaOffer(
            id = "mstislav_boyar",
            warning = "Боярин Мстислав-Свирепый собирает крупные дела под своё крыло — про {name} тоже зашёл разговор. Отказаться нельзя.",
            closure = "Боярин Мстислав-Свирепый поглотил дело — на руки вкладчикам ровно половина"
        ),
        MafiaOffer(
            id = "guild_demand",
            warning = "Купеческая гильдия выставила {name} требование: половину долей в общую казну — иначе прикроют торговлю по всей округе.",
            closure = "Гильдия настояла на своём — вкладчикам осталась лишь половина"
        ),
        MafiaOffer(
            id = "oprichniki",
            warning = "Опричники приходили на двор {name} с проверкой — намекнули, что дело лучше переписать на «своих людей».",
            closure = "Опричники переписали дело на своих — половина возвращена честным вкладчикам"
        ),
        MafiaOffer(
            id = "foreign_guests",
            warning = "Иноземные гости предлагают {name} сделку, от которой нельзя отказаться.",
            closure = "Иноземные гости настояли — половина прибыли уплыла за море"
