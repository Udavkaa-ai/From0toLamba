package com.s0dolamby.game.domain.events

/**
 * «Предложение, от которого нельзя отказаться» — прямой порт
 * tg/server/src/game/mafiaOffers.ts.
 *
 * За 2-3 дня до автозакрытия SURVIVOR/UNICORN с шансом 60% делу делают
 * предложение. Игрок видит весть-предупреждение в новостях: если успеет
 * выйти руками (exitProject) — заберёт деньги по обычным правилам; если
 * поленится и дотянет до автозакрытия — получит только 50% от итога.
 *
 * Тексты в стиле «русский народ, старые времена» — дореволюционный
 * купеческий быт, без современных слов «мафия» и пр.
 */
data class MafiaOffer(
    val id: String,
    /** Что появилось в вестях, шаблон с {name}. */
    val warning: String,
    /** Что появится в Летописи как closureReason, если игрок зевнул. */
    val closure: String
)

object MafiaOffers {

    /** Окно появления предложения (за сколько дней до автозакрытия). */
    val OFFER_DAYS_BEFORE = setOf(2, 3)

    /** Вероятность выпадения предложения в окне. */
    const val OFFER_CHANCE = 0.6

    /** Доля от currentValueRubles, которую игрок получит, если зевнёт. */
    const val FORCED_CLOSURE_RETURN_PERCENT = 0.5

    val ALL: List<MafiaOffer> = listOf(
        MafiaOffer(
            id = "voevoda_nephew",
            warning = "Воевода прислал гонца — намекают, что {name} лучше переписать на его племянника, иначе хлопоты будут.",
