/** Окно появления предложения (за сколько дней до автозакрытия) */
export const MAFIA_OFFER_DAYS_BEFORE = [2, 3] as const

/** Вероятность выпадения предложения в окне */
export const MAFIA_OFFER_CHANCE = 0.6

/** Доля от currentValueRubles, которую игрок получит, если зевнёт */
export const MAFIA_FORCED_CLOSURE_RETURN_PERCENT = 0.5

/** Детерминированно по projectId выбирает шаблон. Один проект — одно предложение. */
export function pickMafiaOffer(projectId: string): MafiaOffer {
  const seed = projectId.split('').reduce((s, c) => s + c.charCodeAt(0), 0)
  return MAFIA_OFFERS[seed % MAFIA_OFFERS.length]
}

/** Подставляет {name} в шаблон */
export function renderMafiaText(template: string, projectName: string): string {
  return template.replace(/\{name\}/g, projectName)
}
