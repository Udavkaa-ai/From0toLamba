/** Вернуть справку по любому enum-ID (нужно модалке подвига) */
export function loreFor(kind: 'type' | 'archetype' | 'fate', id: string): LoreEntry | null {
  if (kind === 'type')      return TYPE_LORE[id] ?? null
  if (kind === 'archetype') return ARCHETYPE_LORE[id] ?? null
  if (kind === 'fate')      return FATE_LORE[id] ?? null
  return null
}
